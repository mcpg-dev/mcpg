/// The scheme that marks a `--config` value as a client-encrypted address. It
/// is the whole signal — no content-type sniffing, no body probing — because
/// the alternative is guessing, and a guess that lands wrong surfaces much
/// later as an unexplained YAML parse error.
pub const SCHEME: &str = "mcpg+enc:";

/// Names the construction: key derivation, AEAD, and the AAD field tuple
/// together. It is the first token of the AAD, so it is inside the tag.
pub const CONSTRUCTION: &str = "mcpg-config-v1";
/// HKDF label for the AES key. The other two labels belong to values only a
/// publisher or an editor produces, so the gateway has no use for them.
const INFO_KEY: &str = "mcpg-config-v1/key";
/// The only key derivation this gateway opens. A passphrase-derived config
/// (`pbkdf2-sha256`) is refused by name rather than attempted.
const KDF_HKDF: &str = "hkdf-sha256";

/// Marker on the JSON document inside the ciphertext.
pub const PLAINTEXT_DOC: &str = "mcpg.config/v1";
/// The only plaintext encoding this construction defines.
pub const PLAINTEXT_FORMAT: &str = "yaml";

/// Human-facing prefix on the secret. Not key material — stripped before
/// decoding. It exists so secret scanners have a rule to match, so an error can
/// say "that is not a config secret" instead of "decryption failed", and so a
/// secret is recognisable in a paste.
pub const SECRET_PREFIX: &str = "mcpg_sk_";
/// Crockford base32 minus `i`, `l`, `o`, `u`: no glyph a human can transcribe
/// two ways.
const CROCKFORD: &[u8; 32] = b"0123456789abcdefghjkmnpqrstvwxyz";
/// 32 bytes at 5 bits a character.
const SECRET_BODY_CHARS: usize = 52;
const SECRET_BYTES: usize = 32;
/// 16 bytes at 5 bits a character. 128 random bits, so ids cannot be walked.
const ID_CHARS: usize = 26;
const NONCE_BYTES: usize = 12;
const TAG_BYTES: usize = 16;
const SALT_BYTES: usize = 16;
/// Cap on the decrypted document. A gateway config is a few KiB.
const MAX_PLAINTEXT_BYTES: usize = 1024 * 1024;

/// Holds one secret, read from a file so a Kubernetes Secret can mount it.
/// The documented preference: an environment variable is readable through
/// `/proc/<pid>/environ` for the life of the process and lands in core dumps,
/// and this gateway does not try to hide it afterwards — unsetting a variable
/// while other threads may be reading the environment is undefined behaviour,
/// and a documented exposure beats one papered over with a data race.
pub const SECRET_FILE_ENV: &str = "MCPG_CONFIG_SECRET_FILE";
/// Holds one secret inline. See [`SECRET_FILE_ENV`] for why that is preferred.
pub const SECRET_ENV: &str = "MCPG_CONFIG_SECRET";
/// Path to a `{"<id>": "mcpg_sk_…"}` JSON map, for a boot with several
/// encrypted layers. Resolves *which* secret applies to *which* layer
/// explicitly rather than trying every secret against every blob.
pub const SECRETS_FILE_ENV: &str = "MCPG_CONFIG_SECRETS_FILE";
/// Refuse any encrypted layer published below this version. A partial defence
/// against a host that answers "latest" with an older but genuinely authentic
/// version; the pinned `/v/<n>` address is the complete one.
pub const MIN_VERSION_ENV: &str = "MCPG_CONFIG_MIN_VERSION";

/// Why an encrypted layer could not be turned into YAML. The variants are
/// separate because the operator's next move differs: fix the secret, ask the
/// publisher to re-publish, or report a broken payload.
#[derive(Debug)]
pub enum DecryptFailure {
    /// The secret, the payload, or the decrypted document is not the shape
    /// `mcpg-config-v1` defines. Nothing was decrypted.
    Malformed(String),
    /// AES-GCM authentication failed.
    WrongSecret { id: String },
    /// The authenticated expiry is in the past.
    Expired { id: String, expires_at: i64 },
}

impl std::fmt::Display for DecryptFailure {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Malformed(detail) => write!(f, "malformed encrypted config: {detail}"),
            Self::WrongSecret { id } => write!(
                f,
                "wrong config secret for {id}: AES-GCM authentication failed. The secret, the \
                 config id, the version, the expiry and the one-time flag are authenticated \
                 together, so a secret minted for a different config fails here too. Check the \
                 value you supplied via {SECRET_FILE_ENV} / {SECRET_ENV} / {SECRETS_FILE_ENV} / \
                 `#k=`."
            ),
            Self::Expired { id, expires_at } => write!(
                f,
                "config {id} expired at unix {expires_at}. The expiry is authenticated, so only \
                 the secret holder can change it — re-publish the config with a new expiry."
            ),
        }
    }
}

impl std::error::Error for DecryptFailure {}

fn malformed(detail: impl Into<String>) -> DecryptFailure {
    DecryptFailure::Malformed(detail.into())
}

/// The 32 secret bytes, wiped on drop. `Debug` renders nothing, so the secret
/// cannot reach a log through `tracing::info!(?x)` or a panic message.
pub struct ConfigSecret {
    bytes: [u8; SECRET_BYTES],
}

impl std::fmt::Debug for ConfigSecret {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("ConfigSecret(***)")
    }
}

impl Drop for ConfigSecret {
    fn drop(&mut self) {
        self.bytes.zeroize();
    }
}

/// Parse the presentation form: `mcpg_sk_` + 52 Crockford base32 characters.
///
/// The prefix is optional on input and stripped before decoding — it is a
/// recognition aid, not key material, so both spellings decode to the same
/// bytes. Whitespace goes first, because a secret arrives through a password
/// manager or a wrapped email as often as through a clean paste.
pub fn parse_secret(raw: &str) -> Result<ConfigSecret, DecryptFailure> {
    let compact: String = raw
        .chars()
        .filter(|c| !c.is_whitespace())
        .flat_map(char::to_lowercase)
        .collect();
    let body = compact.strip_prefix(SECRET_PREFIX).unwrap_or(&compact);
    if body.len() != SECRET_BODY_CHARS {
        return Err(malformed(format!(
            "a config secret is `{SECRET_PREFIX}` and {SECRET_BODY_CHARS} characters; this one \
             has {} characters after the prefix",
            body.len()
        )));
    }
    let mut decoded = decode_crockford(body)?;
    if decoded.len() < SECRET_BYTES {
        decoded.zeroize();
        return Err(malformed("a config secret decodes to 32 bytes"));
    }
    let mut bytes = [0u8; SECRET_BYTES];
    bytes.copy_from_slice(&decoded[..SECRET_BYTES]);
    decoded.zeroize();
    Ok(ConfigSecret { bytes })
}

/// Crockford base32, most-significant bit first, no padding — the mirror of the
/// publisher's encoder. A trailing partial group is dropped, exactly as the
/// encoder's leftover bits were padding rather than data.
fn decode_crockford(text: &str) -> Result<Vec<u8>, DecryptFailure> {
    let mut bits = 0u32;
    let mut value = 0u32;
    let mut out = Vec::with_capacity(text.len() * 5 / 8);
    for ch in text.bytes() {
        let Some(idx) = CROCKFORD.iter().position(|c| *c == ch) else {
            return Err(malformed(format!(
                "a config secret is Crockford base32 ({}); `{}` is not in that alphabet",
                String::from_utf8_lossy(CROCKFORD),
                ch as char
            )));
        };
        value = (value << 5) | idx as u32;
        bits += 5;
        if bits >= 8 {
            out.push(((value >> (bits - 8)) & 0xff) as u8);
            bits -= 8;
        }
    }
    Ok(out)
}

/// Whether a string is shaped like a config id: 26 Crockford base32 characters.
#[must_use]
pub fn is_config_id(value: &str) -> bool {
    value.len() == ID_CHARS && value.bytes().all(|b| CROCKFORD.contains(&b))
}

/// The exact byte string the tag covers. Only ever constructed, never parsed.
///
/// The other implementation is `apps/cloud/config/src/aad.rs`; the golden
/// vector test is what keeps them byte-identical.
#[must_use]
pub fn aad(
    id: &str,
    version: u64,
    expires_at: i64,
    one_time_read: bool,
    kdf_salt: &[u8],
) -> String {
    format!(
        "{CONSTRUCTION}|{id}|{version}|{expires_at}|{}|{}",
        u8::from(one_time_read),
        URL_SAFE_NO_PAD.encode(kdf_salt)
    )
}

/// One encrypted payload, as fetched. Every field but `id` comes off the wire;
/// `id` is the one the gateway asked for, and that asymmetry is the point.
#[derive(Debug)]
pub struct EncryptedPayload {
    /// From the URL, never from the response.
    pub id: String,
    pub version: u64,
    /// Unix seconds UTC.
    pub expires_at: i64,
    pub one_time_read: bool,
    pub kdf: String,
    pub kdf_salt: Vec<u8>,
    pub nonce: Vec<u8>,
    /// Ciphertext with the 16-byte tag appended.
    pub ciphertext: Vec<u8>,
    /// What the host says the associated data is. Diagnostic only: the value
    /// actually used is rebuilt locally, and a disagreement is a named error.
    pub served_aad: Option<String>,
}

impl EncryptedPayload {
    fn check_shape(&self) -> Result<(), DecryptFailure> {
        if !is_config_id(&self.id) {
            return Err(malformed(format!(
                "`{}` is not a config id: {ID_CHARS} Crockford base32 characters",
                self.id
            )));
        }
        if self.kdf != KDF_HKDF {
            return Err(malformed(format!(
                "this config was published with `{}`; the gateway opens `{KDF_HKDF}` configs \
                 only. A passphrase-derived config has to be decrypted where the passphrase is.",
                self.kdf
            )));
        }
        if self.version < 1 {
            return Err(malformed("a config version starts at 1"));
        }
        if self.kdf_salt.len() != SALT_BYTES {
            return Err(malformed(format!(
                "`kdf_salt` is {} bytes, this construction uses {SALT_BYTES}",
                self.kdf_salt.len()
            )));
        }
        if self.nonce.len() != NONCE_BYTES {
            return Err(malformed(format!(
                "`nonce` is {} bytes, AES-GCM takes {NONCE_BYTES}",
                self.nonce.len()
            )));
        }
        if self.ciphertext.len() <= TAG_BYTES {
            return Err(malformed(format!(
                "the payload is {} bytes, which cannot hold a {TAG_BYTES}-byte tag and a document",
                self.ciphertext.len()
            )));
        }
        if self.ciphertext.len() - TAG_BYTES > MAX_PLAINTEXT_BYTES {
            return Err(malformed(format!(
                "the decrypted document would be {} bytes, over the {MAX_PLAINTEXT_BYTES}-byte cap",
                self.ciphertext.len() - TAG_BYTES
            )));
        }
        Ok(())
    }

    /// The associated data this gateway will authenticate against — built from
    /// the id it asked for, never the id it was told.
    #[must_use]
    pub fn aad(&self) -> String {
        aad(
            &self.id,
            self.version,
            self.expires_at,
            self.one_time_read,
            &self.kdf_salt,
        )
    }
}

/// The JSON document inside the ciphertext. Advisory display metadata is
/// optional and unknown keys are tolerated: this side of the tag is written by
/// whoever holds the secret, and a new display field must not break an old
/// gateway.
#[derive(Debug, Deserialize)]
struct PlaintextEnvelope {
    doc: String,
    format: String,
    config: String,
    #[serde(default)]
    name: Option<String>,
}

/// A decrypted layer. `name` is advisory — it never reaches the origin label.
#[derive(Debug)]
pub struct DecryptedConfig {
    pub id: String,
    pub version: u64,
    pub name: Option<String>,
    pub yaml: String,
}

/// Derive the AES-256-GCM key. RFC 5869 with the construction's own label, so a
/// secret cannot be replayed as any other secret-derived value.
fn derive_cipher(secret: &ConfigSecret, salt: &[u8]) -> Result<Aes256Gcm, DecryptFailure> {
    let hk = hkdf::Hkdf::<sha2::Sha256>::new(Some(salt), &secret.bytes);
    let mut key = [0u8; 32];
    hk.expand(INFO_KEY.as_bytes(), &mut key)
        .map_err(|_| malformed("key derivation produced the wrong length"))?;
    let cipher = Aes256Gcm::new_from_slice(&key)
        .map_err(|_| malformed("derived key is not a valid AES-256 key"));
    key.zeroize();
    cipher
}

/// Open one payload. `now_unix` is a parameter so the expiry check is testable
/// without waiting for a clock.
pub fn open(
    payload: &EncryptedPayload,
    secret: &ConfigSecret,
    now_unix: i64,
) -> Result<DecryptedConfig, DecryptFailure> {
    payload.check_shape()?;

    // Rebuilt locally, then compared. The comparison buys a straight answer
    // rather than a security property: both strings are ours to compute, so a
    // host running a different construction gets named as such instead of
    // presenting as a wrong secret.
    let aad = payload.aad();
    if let Some(served) = &payload.served_aad
        && served != &aad
    {
        return Err(malformed(format!(
            "the host says this config is bound to {served:?}, but the address and parameters it \
             served describe {aad:?} — it is running a different construction"
        )));
    }

    let cipher = derive_cipher(secret, &payload.kdf_salt)?;
    let plaintext = cipher
        .decrypt(
            Nonce::from_slice(&payload.nonce),
            Payload {
                msg: &payload.ciphertext,
                aad: aad.as_bytes(),
            },
        )
        .map_err(|_| DecryptFailure::WrongSecret {
            id: payload.id.clone(),
        })?;
    if plaintext.len() > MAX_PLAINTEXT_BYTES {
        return Err(malformed(format!(
            "decrypted document is {} bytes, over the {MAX_PLAINTEXT_BYTES}-byte cap",
            plaintext.len()
        )));
    }

    let inner: PlaintextEnvelope = serde_json::from_slice(&plaintext).map_err(|e| {
        malformed(format!(
            "decrypted document is not `{PLAINTEXT_DOC}` JSON: {e}"
        ))
    })?;
    if inner.doc != PLAINTEXT_DOC {
        return Err(malformed(format!(
            "decrypted `doc` is {:?}, expected {PLAINTEXT_DOC:?}",
            inner.doc
        )));
    }
    if inner.format != PLAINTEXT_FORMAT {
        return Err(malformed(format!(
            "decrypted `format` is {:?}, this gateway reads {PLAINTEXT_FORMAT:?}",
            inner.format
        )));
    }

    // Checked after decryption: the host's own expiry sweep is housekeeping,
    // and the authenticated value is the boundary.
    if payload.expires_at != 0 && payload.expires_at <= now_unix {
        return Err(DecryptFailure::Expired {
            id: payload.id.clone(),
            expires_at: payload.expires_at,
        });
    }

    Ok(DecryptedConfig {
        id: payload.id.clone(),
        version: payload.version,
        name: inner.name,
        yaml: inner.config,
    })
}

/// Decode one of the payload route's base64 parameters. Standard alphabet with
/// padding, which is what the service emits.
pub fn decode_b64(field: &str, value: &str) -> Result<Vec<u8>, DecryptFailure> {
    B64.decode(value.trim())
        .map_err(|e| malformed(format!("`{field}` is not standard base64: {e}")))
}

/// The downgrade floor from [`MIN_VERSION_ENV`], if the operator set one.
pub fn min_version() -> Result<Option<u64>> {
    let Some(raw) = std::env::var_os(MIN_VERSION_ENV) else {
        return Ok(None);
    };
    let raw = raw.to_string_lossy();
    let trimmed = raw.trim();
    if trimmed.is_empty() {
        return Ok(None);
    }
    let parsed: u64 = trimmed
        .parse()
        .with_context(|| format!("{MIN_VERSION_ENV} must be a version number, got {trimmed:?}"))?;
    Ok(Some(parsed))
}

