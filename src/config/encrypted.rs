    /// Render raw bytes the way a publisher does, so the tests exercise the
    /// presentation form rather than the parser's own inverse.
    fn secret_text(bytes: &[u8; SECRET_BYTES]) -> String {
        let mut bits = 0u32;
        let mut value = 0u32;
        let mut out = String::new();
        for b in bytes {
            value = (value << 8) | u32::from(*b);
            bits += 8;
            while bits >= 5 {
                out.push(CROCKFORD[((value >> (bits - 5)) & 31) as usize] as char);
                bits -= 5;
            }
        }
        if bits > 0 {
            out.push(CROCKFORD[((value << (5 - bits)) & 31) as usize] as char);
        }
        format!("{SECRET_PREFIX}{}", &out[..SECRET_BODY_CHARS])
    }

    fn raw(text: &str) -> [u8; SECRET_BYTES] {
        parse_secret(text).unwrap().bytes
    }

    #[test]
    fn a_secret_round_trips_through_the_presentation_form() {
        let bytes = [7u8; SECRET_BYTES];
        let text = secret_text(&bytes);
        assert_eq!(text.len(), SECRET_PREFIX.len() + SECRET_BODY_CHARS);
        assert_eq!(raw(&text), bytes);
        // The prefix is a recognition aid, not key material.
        assert_eq!(raw(text.strip_prefix(SECRET_PREFIX).unwrap()), bytes);
        // Whitespace a password manager or a wrapped email inserted.
        assert_eq!(raw(&format!("  {} \n", text.replace("77", "77 "))), bytes);
    }

