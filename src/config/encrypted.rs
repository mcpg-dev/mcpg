/// Split a `#k=…` fragment off a `--config` value, returning the URL to fetch
/// and the secret it carried. Grammar: `&`-separated params split on the FIRST
/// `=`; only `k` is defined, unknown params are ignored, and a bare `#anchor`
/// with no `=` is not key material — an ordinary anchor must never be mistaken
/// for a secret. The fragment is removed before anything else touches the
/// value, so it cannot reach `origin_label()` and the audit trail.
#[must_use]
pub fn split_fragment(spec: &str) -> (&str, Option<Sensitive<String>>) {
    let Some((url, fragment)) = spec.split_once('#') else {
        return (spec, None);
    };
    let key = fragment.split('&').find_map(|param| {
        let (name, value) = param.split_once('=')?;
        (name == "k").then(|| Sensitive::new(value.to_owned()))
    });
    (url, key)
}

/// The same value with any `k` fragment param masked, for the one place a
/// `--config` spec is echoed verbatim: the error context wrapping a failed
/// layer. An operator pastes the whole share link often enough that the naive
/// `format!("--config {spec}")` would print the secret on any boot failure.
#[must_use]
pub fn redacted_spec(spec: &str) -> String {
    let Some((url, fragment)) = spec.split_once('#') else {
        return spec.to_owned();
    };
    let masked: Vec<String> = fragment
        .split('&')
        .map(|param| match param.split_once('=') {
            Some(("k", _)) => "k=***".to_owned(),
            _ => param.to_owned(),
        })
        .collect();
    format!("{url}#{}", masked.join("&"))
}

/// Find the secret for one encrypted layer. First hit wins, and a miss is a
/// hard error naming the id — never a silent skip and never a plaintext
/// fallthrough.
pub fn resolve_secret(id: &str, fragment: Option<&Sensitive<String>>) -> Result<ConfigSecret> {
    let candidate = if let Some(from_fragment) = fragment {
        from_fragment.clone()
    } else if let Some(from_map) = secret_from_secrets_file(id)? {
        from_map
    } else if let Some(from_env) = env_secret()? {
        from_env
    } else if let Some(typed) = prompt_for_secret(id)? {
        typed
    } else {
        bail!(
            "no config secret for {id}. Supply one of: `{SECRET_FILE_ENV}=<path to a file holding \
             {SECRET_PREFIX}…>` (preferred — a Kubernetes Secret mounts as a file, and an \
             environment variable is readable through /proc/<pid>/environ), \
             `{SECRET_ENV}={SECRET_PREFIX}…`, `{SECRETS_FILE_ENV}=<path to a 0600 JSON map of id \
             → secret>`, or a `#k={SECRET_PREFIX}…` fragment on the --config address."
        )
    };
    Ok(parse_secret(candidate.expose())?)
}

/// Cached because a later encrypted layer needs the same value and re-reading
/// a file per layer would be a second chance to fail halfway through a boot.
static ENV_SECRET: OnceLock<Result<Option<Sensitive<String>>, String>> = OnceLock::new();

fn env_secret() -> Result<Option<Sensitive<String>>> {
    ENV_SECRET
        .get_or_init(|| read_env_secret().map_err(|e| format!("{e:#}")))
        .clone()
        .map_err(|e| anyhow::anyhow!(e))
}

fn read_env_secret() -> Result<Option<Sensitive<String>>> {
    // No permission gate on this one: the documented deployment is a
    // Kubernetes Secret volume, which mounts world-readable by default, and
    // refusing to boot on the recommended shape would push operators back to
    // the env-var form this file exists to replace.
    let from_file = match std::env::var(SECRET_FILE_ENV) {
        Ok(raw) if !raw.trim().is_empty() => {
            let path = PathBuf::from(raw.trim());
            let text = std::fs::read_to_string(&path)
                .with_context(|| format!("{SECRET_FILE_ENV}: read {}", path.display()))?;
            Some(text.trim().to_owned())
        }
        _ => None,
    };
    let inline = std::env::var(SECRET_ENV)
        .ok()
        .map(|v| v.trim().to_owned())
        .filter(|v| !v.is_empty());
    reconcile_env_secret(from_file, inline)
}

/// The file form wins, but two DIFFERENT values are a contradiction rather
/// than a precedence question — the operator meant one of them.
fn reconcile_env_secret(
    from_file: Option<String>,
    inline: Option<String>,
) -> Result<Option<Sensitive<String>>> {
    match (from_file, inline) {
        (Some(file), Some(env)) if file != env => {
            bail!(
                "{SECRET_FILE_ENV} and {SECRET_ENV} are both set and hold different secrets — \
                 unset one"
            )
        }
        (Some(value), _) | (None, Some(value)) => Ok(Some(Sensitive::new(value))),
        (None, None) => Ok(None),
    }
}

fn secret_from_secrets_file(id: &str) -> Result<Option<Sensitive<String>>> {
    let Some(raw) = std::env::var_os(SECRETS_FILE_ENV) else {
        return Ok(None);
    };
    let path = PathBuf::from(raw);
    if path.as_os_str().is_empty() {
        return Ok(None);
    }
    enforce_owner_only(&path, SECRETS_FILE_ENV)?;
    let text = std::fs::read_to_string(&path)
        .with_context(|| format!("{SECRETS_FILE_ENV}: read {}", path.display()))?;
    let map: BTreeMap<String, String> = serde_json::from_str(&text).with_context(|| {
        format!(
            "{SECRETS_FILE_ENV} ({}) must be a JSON object of config id → secret",
            path.display()
        )
    })?;
    Ok(map
        .get(id)
        .map(|k| Sensitive::new(k.trim().to_owned()))
        .filter(|k| !k.expose().is_empty()))
}

/// A secret MAP is operator-authored on a workstation, so its permissions are
/// the operator's to get right — and a world-readable one hands over every
/// config at once.
#[cfg(unix)]
fn enforce_owner_only(path: &Path, var: &str) -> Result<()> {
    use std::os::unix::fs::PermissionsExt as _;
    let mode = std::fs::metadata(path)
        .with_context(|| format!("{var}: stat {}", path.display()))?
        .permissions()
        .mode();
    if mode & 0o077 != 0 {
        bail!(
            "{var} ({}) is mode {:04o}; a file holding config secrets must be readable by its \
             owner only — `chmod 600 {}`",
            path.display(),
            mode & 0o7777,
            path.display()
        );
    }
    Ok(())
}

#[cfg(not(unix))]
fn enforce_owner_only(_path: &Path, _var: &str) -> Result<()> {
    Ok(())
}

fn prompt_for_secret(id: &str) -> Result<Option<Sensitive<String>>> {
    if !std::io::stdin().is_terminal() {
        return Ok(None);
    }
    let mut err = std::io::stderr();
    write!(err, "config secret for {id} (input is hidden): ").ok();
    err.flush().ok();
    let typed = read_line_no_echo()?;
    writeln!(err).ok();
    let typed = typed.trim().to_owned();
    Ok((!typed.is_empty()).then(|| Sensitive::new(typed)))
}

#[cfg(unix)]
fn read_line_no_echo() -> Result<String> {
    use std::io::BufRead as _;

    let fd = libc::STDIN_FILENO;
    let mut term: libc::termios = unsafe { std::mem::zeroed() };
    // SAFETY: `fd` is stdin and known to be a terminal (checked by the caller);
    // `term` is a live, correctly sized `termios`.
    if unsafe { libc::tcgetattr(fd, &mut term) } != 0 {
        bail!("cannot read terminal settings to hide the config secret as it is typed");
    }
    let saved = term;
    term.c_lflag &= !libc::ECHO;
    // SAFETY: same fd, and `term` is the struct just filled by tcgetattr.
    if unsafe { libc::tcsetattr(fd, libc::TCSANOW, &term) } != 0 {
        bail!(
            "cannot turn terminal echo off; refusing to prompt for the config secret in the clear"
        );
    }
    let mut line = String::new();
    let read = std::io::stdin().lock().read_line(&mut line);
    // Restore before propagating: an error must not leave the terminal mute.
    // SAFETY: `saved` is the unmodified struct tcgetattr produced.
    unsafe {
        libc::tcsetattr(fd, libc::TCSANOW, &saved);
    }
    read.context("read the config secret from the terminal")?;
    Ok(line)
}

#[cfg(not(unix))]
fn read_line_no_echo() -> Result<String> {
    bail!(
        "hidden terminal input is not available on this platform — supply the secret via \
         {SECRET_FILE_ENV} or {SECRET_ENV}"
    )
}

#[cfg(test)]
