    /// The vector the browser generated, opened by the code the gateway boots
    /// with.
    ///
    /// Every other test in this file and in `source.rs` seals with this crate's
    /// own helpers and opens with this crate's own code, which is
    /// self-consistent by construction and proves nothing about the publisher.
    /// This is the one that crosses the boundary. If the key derivation, the
    /// AAD, the secret alphabet, the base64 variant, or the AEAD parameters
    /// drift on either side, one of the two suites fails instead of a user's
    /// boot.
    ///
    /// Regenerate with `node apps/cloud-config/scripts/crypto-vector.mjs
    /// --generate` — and only when the construction itself changes, because a
    /// new vector is a wire break rather than a refresh.
    const VECTOR: &str = include_str!("testdata/config-enc-v1-vector.json");

    #[derive(serde::Deserialize)]
    struct Vector {
        construction: String,
        secret: String,
        id: String,
        version: u64,
        expires_at: i64,
        one_time_read: bool,
        kdf: String,
        kdf_salt_b64: String,
        nonce_b64: String,
        aad: String,
        ciphertext_b64: String,
        yaml: String,
        plaintext_name: String,
    }

    fn vector() -> Vector {
        serde_json::from_str(VECTOR).expect("the committed vector is JSON")
    }

    #[test]
    fn the_browser_s_vector_opens_with_the_gateway_s_code() {
        let v = vector();
        assert_eq!(v.construction, CONSTRUCTION);

        let payload = EncryptedPayload {
            id: v.id.clone(),
            version: v.version,
            expires_at: v.expires_at,
            one_time_read: v.one_time_read,
            kdf: v.kdf.clone(),
            kdf_salt: decode_b64("kdf_salt", &v.kdf_salt_b64).unwrap(),
            nonce: decode_b64("nonce", &v.nonce_b64).unwrap(),
            ciphertext: decode_b64("ct", &v.ciphertext_b64).unwrap(),
            served_aad: Some(v.aad.clone()),
        };
        // Built independently here, then compared: the vector's own string is
        // what the browser produced.
        assert_eq!(payload.aad(), v.aad);

        let secret = parse_secret(&v.secret).expect("the vector's secret parses");
        // One second before the authenticated expiry, so the vector does not
        // start failing when the wall clock passes it.
        let opened = open(&payload, &secret, v.expires_at - 1).expect("the vector decrypts");
        assert_eq!(opened.yaml, v.yaml);
        assert_eq!(opened.id, v.id);
        assert_eq!(opened.version, v.version);
        assert_eq!(opened.name.as_deref(), Some(v.plaintext_name.as_str()));
    }

    #[test]
    fn the_vector_stops_opening_when_a_bound_field_moves() {
        // Guards the vector against passing under a construction that ignores
        // half of what it is supposed to authenticate.
        let v = vector();
        let base = || EncryptedPayload {
            id: v.id.clone(),
            version: v.version,
            expires_at: v.expires_at,
            one_time_read: v.one_time_read,
            kdf: v.kdf.clone(),
            kdf_salt: decode_b64("kdf_salt", &v.kdf_salt_b64).unwrap(),
            nonce: decode_b64("nonce", &v.nonce_b64).unwrap(),
            ciphertext: decode_b64("ct", &v.ciphertext_b64).unwrap(),
            // Dropped: the served string would disagree first and mask the
            // question this test is asking of the tag itself.
            served_aad: None,
        };
        let secret = parse_secret(&v.secret).unwrap();
        let now = v.expires_at - 1;

        let mut moved_expiry = base();
        moved_expiry.expires_at = v.expires_at + 3600;
        assert!(matches!(
            open(&moved_expiry, &secret, now),
            Err(DecryptFailure::WrongSecret { .. })
        ));

        let mut rewound = base();
        rewound.version = v.version - 1;
        assert!(matches!(
            open(&rewound, &secret, now),
            Err(DecryptFailure::WrongSecret { .. })
        ));

        let mut flipped = base();
        flipped.one_time_read = !v.one_time_read;
        assert!(matches!(
            open(&flipped, &secret, now),
            Err(DecryptFailure::WrongSecret { .. })
        ));

        let mut moved = base();
        moved.id = "1a2b3c4d5e6f7g8h9j0kmnpqrs".to_owned();
        assert!(matches!(
            open(&moved, &secret, now),
            Err(DecryptFailure::WrongSecret { .. })
        ));

        // And the expiry is enforced after decryption, not just bound into it.
        assert!(matches!(
            open(&base(), &secret, v.expires_at + 1),
            Err(DecryptFailure::Expired { .. })
        ));
    }

    #[test]
    fn contradictory_env_secret_sources_are_a_boot_error() {
        assert!(reconcile_env_secret(None, None).unwrap().is_none());
        // Same value twice is not a contradiction.
        let agreed = reconcile_env_secret(Some("mcpg_sk_a".into()), Some("mcpg_sk_a".into()))
            .unwrap()
            .unwrap();
        assert_eq!(agreed.expose(), "mcpg_sk_a");
        // The file form wins when only it is set.
        assert_eq!(
            reconcile_env_secret(Some("mcpg_sk_file".into()), None)
                .unwrap()
                .unwrap()
                .expose(),
            "mcpg_sk_file"
        );
        let err = reconcile_env_secret(Some("mcpg_sk_a".into()), Some("mcpg_sk_b".into()))
            .unwrap_err()
            .to_string();
        assert!(
            err.contains(SECRET_FILE_ENV) && err.contains(SECRET_ENV),
            "{err}"
        );
    }
