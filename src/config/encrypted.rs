//! Client-encrypted `--config` layers.
//!
//! A config service stores ciphertext it cannot read: the secret is minted by
//! the publisher — in a browser, or by whatever tool wrote the config — and
//! never reaches the service in any form. A gateway pointed at such an address
//! fetches the payload over an ordinary unauthenticated `GET` (confidentiality
//! is the ciphertext's job, not the endpoint's) and opens it here.
//!
//! The `mcpg-config-v1` construction, which this file implements and
//! `apps/cloud/config/src/aad.rs` implements on the other side:
//!
//! ```text
//! secret  32 random bytes, written as `mcpg_sk_` + 52 Crockford base32 chars
//! key     HKDF-SHA256(ikm = secret, salt = kdf_salt, info = "mcpg-config-v1/key")
//! aad     "mcpg-config-v1|{id}|{version}|{expires_at}|{one_time}|{kdf_salt}"
//! ct      AES-256-GCM(key, nonce[12], aad, plaintext) || tag[16]
//! ```
//!
//! The secret is not the key. Three values come out of the same HKDF with three
//! different labels — the AES key, an edit token, and a burn receipt — and the
//! service is handed only SHA-256 digests of the last two. A value the service
//! has seen must not be the value that decrypts.
//!
//! Everything a reader acts on is inside the tag: `id` stops a blob being
//! transplanted onto another config, `version` stops one being replayed under a
//! different number, and `expires_at`, `one_time` and `kdf_salt` stop the host
//! rewriting the terms of a config it cannot read. **The id used to build that
//! string is the one in the URL that was fetched, never the one in the
//! response** — trusting the response would let a host answer a request for one
//! config with another config's authentic blob, pick that config's key out of
//! the operator's key map, and boot it while the audit trail named the address
//! that was asked for.
//!
//! The plaintext is a JSON envelope rather than raw YAML because the config's
//! name has to be hidden from the service too, and the only place to hide it is
//! inside the ciphertext.
//!
//! Keeping two implementations of one construction in step is what
//! `src/config/testdata/config-enc-v1-vector.json` is for: a vector generated by the
//! browser code, decrypted here.

