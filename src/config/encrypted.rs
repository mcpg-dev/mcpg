/// Where to fetch a payload from, and which config it is.
#[derive(Debug, PartialEq, Eq)]
pub struct Address {
    /// The URL to `GET`.
    pub fetch_url: String,
    pub id: String,
    /// Set when the operator pinned a version. A pinned fetch is the complete
    /// defence against a host that answers "latest" with an older blob.
    pub version: Option<u64>,
}

/// Turn the address an operator pastes into the route that serves bytes.
///
/// Both shapes are accepted because both are handed out: the receipt prints the
/// human `/c/<id>` page, and the publish response also names the machine route
/// for a caller that speaks HTTP directly. Anything else is refused by name
/// rather than fetched hopefully — a wrong path answers `200 text/html` on most
/// hosts, and that would arrive as an unexplained YAML parse error.
pub fn parse_address(url: &str) -> Result<Address> {
    let (without_query, _) = url.split_once('?').unwrap_or((url, ""));
    let trimmed = without_query.trim_end_matches('/');
    let (origin, path) = split_origin(trimmed)?;
    let seg: Vec<&str> = path.split('/').filter(|s| !s.is_empty()).collect();

    let (id, version, prefix): (&str, Option<u64>, &[&str]) = match seg.as_slice() {
        // https://host/c/<id>
        [.., "c", id] => (id, None, &seg[..seg.len() - 2]),
        // https://host/c/<id>/v/<n>
        [.., "c", id, "v", n] => (id, Some(parse_version(n)?), &seg[..seg.len() - 4]),
        // https://host/v1/configs/<id>/ciphertext
        [.., "v1", "configs", id, "ciphertext"] => (id, None, &seg[..seg.len() - 4]),
        // https://host/v1/configs/<id>/versions/<n>/ciphertext
        [.., "v1", "configs", id, "versions", n, "ciphertext"] => {
            (id, Some(parse_version(n)?), &seg[..seg.len() - 6])
        }
        _ => bail!(
            "`{url}` is not a config address. Expected `<host>/c/<id>` (optionally `/v/<n>` to \
             pin a version), or the payload route `<host>/v1/configs/<id>/ciphertext`."
        ),
    };
    if !is_config_id(id) {
        bail!(
            "`{id}` is not a config id: {ID_CHARS} Crockford base32 characters \
             (`0123456789abcdefghjkmnpqrstvwxyz`). A truncated address looks exactly like this."
        );
    }

    let base = if prefix.is_empty() {
        origin.to_owned()
    } else {
        format!("{origin}/{}", prefix.join("/"))
    };
    let fetch_url = match version {
        Some(n) => format!("{base}/v1/configs/{id}/versions/{n}/ciphertext"),
        None => format!("{base}/v1/configs/{id}/ciphertext"),
    };
    Ok(Address {
        fetch_url,
        id: id.to_owned(),
        version,
    })
}

fn parse_version(raw: &str) -> Result<u64> {
    let n: u64 = raw
        .parse()
        .with_context(|| format!("`{raw}` is not a config version"))?;
    if n < 1 {
        bail!("config versions start at 1, not {n}");
    }
    Ok(n)
}

/// Split `scheme://host[:port]` off the path, keeping any path prefix the
/// deployment sits under.
fn split_origin(url: &str) -> Result<(&str, &str)> {
    let after_scheme = url
        .find("://")
        .map(|i| i + 3)
        .context("a config address needs an https:// or http:// scheme")?;
    match url[after_scheme..].find('/') {
        Some(i) => Ok(url.split_at(after_scheme + i)),
        None => Ok((url, "")),
    }
}

